// React 19 + esbuild + lucide-react@0.545 在模块初始化阶段抛 "forwardRef is not a function"。
// 完整迁移时再切换到稳定 icon 库。
//
// 当前策略：保留所有高频 icon 名（以满足源代码 named import），所有 icon 渲染成一个真实的
// inline SVG（用 lucide 原始的 stroke 风格通用 path）。这样 UI 用户**看得见**图标，但
// 都是同一个「盒子+斜线」形状 —— 仅作视觉占位，等真图标库稳定接入再换。
//
// 不依赖任何运行时（除 react）；不会触发 "forwardRef is not a function"。
import type { SVGProps, Ref } from "react";
import { forwardRef } from "react";

const DEFAULT_ICON_PATH =
  "<path d='M21 16V8a2 2 0 0 0-1-1.73l-7-4a2 2 0 0 0-2 0l-7 4A2 2 0 0 0 3 8v8a2 2 0 0 0 1 1.73l7 4a2 2 0 0 0 2 0l7-4A2 2 0 0 0 21 16z'/><polyline points='3.27 6.96 12 12.01 20.73 6.96'/><line x1='12' y1='22.08' x2='12' y2='12'/>";

const Stub = forwardRef<SVGSVGElement, SVGProps<SVGSVGElement>>(function LucideStub(props, _ref) {
  const { width = 16, height = 16, strokeWidth = 2, ...rest } = props;
  // nx-pg：把所有 icon 渲成同一个 16x16 通用「盒子」图标 —— 视觉占位，避免空白。
  // 真图标库接入后会替换为本名对应的真实 SVG path。
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={width}
      height={height}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      // eslint-disable-next-line react/no-danger
      dangerouslySetInnerHTML={{ __html: DEFAULT_ICON_PATH }}
      {...rest}
    />
  );
});

// Proxy 自动创建任意 icon 名（应对 tree-shake 后丢失的命名导出）
const handler: ProxyHandler<object> = {
  get(_target, prop) {
    if (prop === "default") return Stub;
    return Stub;
  },
};
export default new Proxy({}, handler) as typeof import("lucide-react");

